-- Numeração sequencial de pedidos (SQL Editor Supabase).
-- Sem FK para app.tab_venda (editor sem REFERENCES).
-- Desabilita RLS: o role da API precisa INSERT/SELECT sem policy.

CREATE TABLE IF NOT EXISTS public.tab_pedido_numero (
  numero_pedido bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venda uuid NOT NULL UNIQUE,
  telefone_normalizado text NOT NULL,
  data_criacao timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS tab_pedido_numero_tel_idx
  ON public.tab_pedido_numero (telefone_normalizado, numero_pedido);

ALTER TABLE public.tab_pedido_numero DISABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.tab_pedido_numero TO amanteigados_prod_app;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public'
      AND c.relkind = 'S'
      AND c.relname = 'tab_pedido_numero_numero_pedido_seq'
  ) THEN
    EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.tab_pedido_numero_numero_pedido_seq TO amanteigados_prod_app';
  END IF;
END
$$;
