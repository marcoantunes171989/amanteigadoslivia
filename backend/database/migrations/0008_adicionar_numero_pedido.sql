-- Numeração sequencial numérica de pedidos (somente dígitos), sem ALTER em tab_venda.
CREATE TABLE IF NOT EXISTS app.tab_pedido_numero (
  numero_pedido bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_venda uuid NOT NULL UNIQUE,
  telefone_normalizado text NOT NULL,
  data_criacao timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fk_tab_pedido_numero_venda
    FOREIGN KEY (id_venda) REFERENCES app.tab_venda (id_venda) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS tab_pedido_numero_tel_idx
  ON app.tab_pedido_numero (telefone_normalizado, numero_pedido);
